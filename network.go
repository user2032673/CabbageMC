func getPacketID(r *net_structures.PacketBuffer) (int32, error) {
	value, err := r.ReadVarInt()
	if err != nil {
		return 0, err
	}
	return int32(value), nil
}

func readUnsignedShort(r *net_structures.PacketBuffer) (uint16, error) {
	short, err := r.ReadUint16()
	if err != nil {
		return 0, err
	}
	return uint16(short), nil
}

func readVarInt(r *net_structures.PacketBuffer) (int32, error) {
	return getPacketID(r)
}

func readVarLong(r *net_structures.PacketBuffer) (int64, error) {
	long, err := r.ReadVarLong()
	if err != nil {
		return 0, err
	}
	return int64(long), nil
}

func readString(r *net_structures.PacketBuffer, maxLen int) (string, error) {
	str, err := r.ReadString(maxLen)
	if err != nil {
		return "", err
	}
	return string(str), nil
}

func writeGameProfile(w *net_structures.PacketBuffer, profile Profile) error {
	profileConverted := net_structures.GameProfile{
		UUID:     net_structures.UUID(profile.Uuid),
		Username: net_structures.String(profile.Username),
	}

	err := w.WriteGameProfile(net_structures.GameProfile(profileConverted))
	if err != nil {
		return err
	}
	return nil
}

