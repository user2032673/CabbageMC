func getPacketID(r *net_structures.PacketBuffer) (int32, error) {
	value, err := r.ReadVarInt()
	if err != nil {
		return 0, err
	}
	return int32(value), nil
}

func discardVarInt(r *net_structures.PacketBuffer) error {
	_, err := r.ReadVarInt()
	if err != nil {
		return err
	}
	return nil
}

func discardString(r *net_structures.PacketBuffer, maxLen int) error {
	_, err := r.ReadString(maxLen)
	if err != nil {
		return err
	}
	return nil
}

func readVarInt(r *net_structures.PacketBuffer) (int32, error) {
	return getPacketID(r)
}

func readVarLong(r *net_structures.PacketBuffer) (int64, error) {
	long, err := r.ReadVarLong()
	if err != nil {
		return 0, err
	}
	return int64(long), nil
}

func readString(r *net_structures.PacketBuffer, maxLen int) (string, error) {
	str, err := r.ReadString(maxLen)
	if err != nil {
		return "", err
	}
	return string(str), nil
}

func discardNumBytes(r *net_structures.PacketBuffer, numBytes int) error {
	for range numBytes {
		_, err := r.ReadByte()
		if err != nil {
			return err
		}
	}
	return nil
}

func writeVarInt(w *net_structures.PacketBuffer, int int) error {
	err := w.WriteVarInt(net_structures.VarInt(int))
	if err != nil {
		return err
	}
	return nil
}

func writeVarLong(w *net_structures.PacketBuffer, long int64) error {
	err := w.WriteVarLong(net_structures.VarLong(long))
	if err != nil {
		return err
	}
	return nil
}

func writeString(w *net_structures.PacketBuffer, string string) error {
	err := w.WriteString(net_structures.String(string))
	if err != nil {
		return err
	}
	return nil
}

// ======================= HANDSHAKING

type C2SHandshake struct { // PacketID 0x00; HANDSHAKING
	ProtocolVersion int32
	ServerAddress   string
	ServerPort      int16
	Intent          int // 1 = Status; 2 = Login; 3 = Transfer
}

// ======================= STATUS

type C2SStatusRequest struct { // PacketID 0x00; STATUS
	// No fields
}

type S2CStatusResponse struct { // PacketID 0x00; STATUS
	JSONResponse string // JSON text component
}

type C2SPingRequest struct { // PacketID 0x01; STATUS
	Timestamp uint64 // May be any number, but vanilla clients will always use the timestamp in milliseconds.
}

type S2CPongResponse struct { // PacketID 0x01; STATUS
	Timestamp uint64 // Should match the one sent by the client.
}

// ======================= LOGIN

type S2CLoginDisconnect struct { // PacketID 0x00
	Reason string // The reason why the player was disconnected. JSON text component
}

type C2SLoginStart struct { // PacketID 0x00
	Name       string // 16 bytes, player username
	PlayerUUID string // Player UUID.
}

type S2CEncryptionRequest struct { // PacketID 0x01
	ServerID           string // 20 bytes, always empty when sent by the vanilla server.
	PublicKey          string // Actually a Prefixed Array of Bytes; the server's public key, in bytes.
	VerifyToken        string // Actually a Prefixed Array of Bytes; a sequence of random bytes generated by the server.
	ShouldAuthenticate bool   // Whether the client should attempt to authenticate through mojang servers.
}

type C2SEncryptionResponse struct { // PacketID 0x01
	SharedSecret string // Actually a Prefixed Array of Bytes; Shared Secret value, encrypted with the server's public key.
	VerifyToken  string // Actually a Prefixed Array of Bytes; Verify Token value, encrypted with the same public key as the shared secret.
}

type S2CLoginSuccess struct { // PacketID 0x02
	Profile     string // https://minecraft.wiki/w/Java_Edition_protocol/Packets#Game_Profile
	SessionUUID string // UUID;
}

type C2SLoginPluginResponse struct { // PacketID 0x02
	MessageID  int // Should match ID from server
	Data  string // 	Prefixed Optional Varies	Any data, depending on the channel. Only present if the client understood the request. Typically this would be a sequence of fields using standard data types, but some unofficial channels have unusual formats. There is no length prefix that applies to all channel types, but the format specific to the channel may or may not include one or more length prefixes (e.g. for strings).
}


